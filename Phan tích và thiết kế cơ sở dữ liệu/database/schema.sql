CREATE DATABASE IF NOT EXISTS TOPAP
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE TOPAP;
CREATE TABLE VAITRO (
    MaVaiTro INT AUTO_INCREMENT PRIMARY KEY,
    TenVaiTro VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE TAIKHOAN (
    MaTaiKhoan INT AUTO_INCREMENT PRIMARY KEY,
    TenDangNhap VARCHAR(50) NOT NULL UNIQUE,
    MatKhau VARCHAR(255) NOT NULL,
    MaVaiTro INT NOT NULL,
    TrangThai TINYINT DEFAULT 1,

    FOREIGN KEY (MaVaiTro)
        REFERENCES VAITRO(MaVaiTro)
);
CREATE TABLE TOANHA (
    MaToaNha INT AUTO_INCREMENT PRIMARY KEY,
    TenToaNha VARCHAR(100) NOT NULL,
    DiaChi VARCHAR(255),
    MoTa TEXT
);

CREATE TABLE CANHO (
    MaCanHo INT AUTO_INCREMENT PRIMARY KEY,
    MaToaNha INT NOT NULL,
    SoCanHo VARCHAR(20) NOT NULL,
    DienTich DECIMAL(8,2),
    Tang INT,
    TrangThai VARCHAR(30) DEFAULT 'Dang su dung',
    UNIQUE (MaToaNha, SoCanHo),
    FOREIGN KEY (MaToaNha) REFERENCES TOANHA(MaToaNha)
);

CREATE TABLE HOGIADINH (
    MaHoGiaDinh INT AUTO_INCREMENT PRIMARY KEY,
    MaCanHo INT NOT NULL,
    TenChuHo VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(20),
    Email VARCHAR(100),
    FOREIGN KEY (MaCanHo) REFERENCES CANHO(MaCanHo)
);

CREATE TABLE CUDAN (
    MaCuDan INT AUTO_INCREMENT PRIMARY KEY,
    MaTaiKhoan INT,
    MaHoGiaDinh INT NOT NULL,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE,
    GioiTinh VARCHAR(10),
    SoDienThoai VARCHAR(20),
    Email VARCHAR(100),
    FOREIGN KEY (MaTaiKhoan) REFERENCES TAIKHOAN(MaTaiKhoan),
    FOREIGN KEY (MaHoGiaDinh) REFERENCES HOGIADINH(MaHoGiaDinh)
);

CREATE TABLE PHUONGTIEN (
    MaPhuongTien INT AUTO_INCREMENT PRIMARY KEY,
    MaCuDan INT NOT NULL,
    LoaiPhuongTien VARCHAR(50),
    BienSo VARCHAR(20) NOT NULL UNIQUE,
    FOREIGN KEY (MaCuDan) REFERENCES CUDAN(MaCuDan)
);

CREATE TABLE LOAIPHI (
    MaLoaiPhi INT AUTO_INCREMENT PRIMARY KEY,
    TenLoaiPhi VARCHAR(100) NOT NULL,
    DonGia DECIMAL(12,2) NOT NULL,
    DonViTinh VARCHAR(30),
    MoTa TEXT
);

CREATE TABLE CHISODIENNUOC (
    MaChiSo INT AUTO_INCREMENT PRIMARY KEY,
    MaCanHo INT NOT NULL,
    LoaiChiSo VARCHAR(20) NOT NULL,
    ChiSoCu DECIMAL(12,2) NOT NULL,
    ChiSoMoi DECIMAL(12,2) NOT NULL,
    NgayGhi DATE NOT NULL,
    FOREIGN KEY (MaCanHo) REFERENCES CANHO(MaCanHo)
);

CREATE TABLE HOADON (
    MaHoaDon INT AUTO_INCREMENT PRIMARY KEY,
    MaHoGiaDinh INT NOT NULL,
    NgayLap DATE NOT NULL,
    HanThanhToan DATE,
    TongTien DECIMAL(12,2) DEFAULT 0,
    TrangThai VARCHAR(30) DEFAULT 'Chua thanh toan',
    FOREIGN KEY (MaHoGiaDinh) REFERENCES HOGIADINH(MaHoGiaDinh)
);

CREATE TABLE CHITIETHOADON (
    MaChiTiet INT AUTO_INCREMENT PRIMARY KEY,
    MaHoaDon INT NOT NULL,
    MaLoaiPhi INT NOT NULL,
    SoLuong DECIMAL(12,2) DEFAULT 1,
    DonGia DECIMAL(12,2) NOT NULL,
    ThanhTien DECIMAL(12,2) NOT NULL,
    FOREIGN KEY (MaHoaDon) REFERENCES HOADON(MaHoaDon),
    FOREIGN KEY (MaLoaiPhi) REFERENCES LOAIPHI(MaLoaiPhi)
);

CREATE TABLE KHACH (
    MaKhach INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(20),
    BienSoXe VARCHAR(20),
    NgayDen DATETIME,
    NgayDi DATETIME,
    MaCanHo INT,
    FOREIGN KEY (MaCanHo) REFERENCES CANHO(MaCanHo)
);

CREATE TABLE TIENICH (
    MaTienIch INT AUTO_INCREMENT PRIMARY KEY,
    TenTienIch VARCHAR(100) NOT NULL,
    MoTa TEXT,
    SucChua INT,
    PhiSuDung DECIMAL(12,2) DEFAULT 0,
    TrangThai VARCHAR(30) DEFAULT 'Hoat dong'
);

CREATE TABLE DATCHOTIENICH (
    MaDatCho INT AUTO_INCREMENT PRIMARY KEY,
    MaTienIch INT NOT NULL,
    MaCuDan INT NOT NULL,
    NgayDat DATE NOT NULL,
    GioBatDau TIME,
    GioKetThuc TIME,
    TrangThai VARCHAR(30) DEFAULT 'Cho xac nhan',
    FOREIGN KEY (MaTienIch) REFERENCES TIENICH(MaTienIch),
    FOREIGN KEY (MaCuDan) REFERENCES CUDAN(MaCuDan)
);

CREATE TABLE YEUCAUSUACHUA (
    MaYeuCau INT AUTO_INCREMENT PRIMARY KEY,
    MaCuDan INT NOT NULL,
    MaNhanVien INT,
    TieuDe VARCHAR(200) NOT NULL,
    MoTa TEXT,
    NgayGui DATETIME DEFAULT CURRENT_TIMESTAMP,
    TrangThai VARCHAR(30) DEFAULT 'Moi',
    FOREIGN KEY (MaCuDan) REFERENCES CUDAN(MaCuDan),
    FOREIGN KEY (MaNhanVien) REFERENCES TAIKHOAN(MaTaiKhoan)
);

CREATE TABLE HINHANH_YEUCAU (
    MaHinhAnh INT AUTO_INCREMENT PRIMARY KEY,
    MaYeuCau INT NOT NULL,
    DuongDan VARCHAR(255) NOT NULL,
    FOREIGN KEY (MaYeuCau) REFERENCES YEUCAUSUACHUA(MaYeuCau)
);

CREATE TABLE THONGBAO (
    MaThongBao INT AUTO_INCREMENT PRIMARY KEY,
    MaTaiKhoan INT,
    TieuDe VARCHAR(200) NOT NULL,
    NoiDung TEXT NOT NULL,
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP,
    DaDoc TINYINT DEFAULT 0,
    FOREIGN KEY (MaTaiKhoan) REFERENCES TAIKHOAN(MaTaiKhoan)
);